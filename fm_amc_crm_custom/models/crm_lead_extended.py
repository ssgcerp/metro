# -*- coding: utf-8 -*-

from odoo import models, fields, api
import logging

_logger = logging.getLogger(__name__)


class CrmLead(models.Model):
    _inherit = 'crm.lead'

    lead_sequence = fields.Char(string='Lead Sequence', 
                              help='Unique sequence generated by Lead Configuration',
                              copy=False, readonly=True, default='New')

    # Lead number field - unique identifier
    lead_number = fields.Char(string='Lead Number', 
                             help='Unique lead number for this opportunity',
                             copy=False)
    
    # Sales agent field
    sales_agent = fields.Char(string='Sales Agent', 
                             help='Sales agent for this opportunity')
    
    _sql_constraints = [
        ('lead_number_unique', 'UNIQUE(lead_number)', 'Lead Number must be unique!')
    ]

    @api.model_create_multi
    def create(self, vals_list):
        _logger.info(f"CRMLEAD CREATE VALS: {vals_list}")
        leads = super().create(vals_list)
        
        config = self.env['crm.lead.config'].get_config()
        
        for lead in leads:
            if lead.lead_sequence == 'New':
                # Get branch code and year directly from the created lead record
                branch_code = None
                company = lead.company_id
                if company:
                    if hasattr(company, 'branch_code') and company.branch_code:
                        branch_code = company.branch_code
                    else:
                        branch_code = getattr(company, 'abbreviation', None) or company.name[:3].upper() if company.name else None
                
                year = lead.create_date.year if lead.create_date else fields.Date.today().year
                
                new_sequence = config.generate_lead_sequence(branch_code=branch_code, year=year)
                if new_sequence:
                    lead.lead_sequence = new_sequence
                    
        return leads

    def write(self, vals):
        res = super().write(vals)
        if 'company_id' in vals:
            import re
            config = self.env['crm.lead.config'].get_config()
            for lead in self:
                if lead.lead_sequence and lead.lead_sequence != 'New':
                    # Extract the old sequence number from the existing lead sequence string
                    # Extract digit sequences. Filter out the year to find the actual sequence number.
                    year_str = str(lead.create_date.year if lead.create_date else fields.Date.today().year)
                    all_numbers = re.findall(r'\d+', lead.lead_sequence)
                    
                    # Remove the year from the list of numbers if it exists
                    candidate_numbers = [n for n in all_numbers if n != year_str and n != str(year_str)[-2:]]
                    
                    if candidate_numbers:
                        # Take the first non-year number
                        old_num = int(candidate_numbers[-1])
                        
                        # Get new branch code
                        branch_code = None
                        company = lead.company_id
                        if company:
                            if hasattr(company, 'branch_code') and company.branch_code:
                                branch_code = company.branch_code
                            else:
                                branch_code = getattr(company, 'abbreviation', None) or company.name[:3].upper() if company.name else None
                        
                        year = lead.create_date.year if lead.create_date else fields.Date.today().year
                        
                        # Regenerate sequence string preserving the numeric sequence
                        new_sequence = config.generate_lead_sequence(
                            branch_code=branch_code, 
                            year=year, 
                            force_sequence_number=old_num
                        )
                        
                        if new_sequence and new_sequence != lead.lead_sequence:
                            # Avoid recursive write
                            super(CrmLead, lead).write({'lead_sequence': new_sequence})
        return res

