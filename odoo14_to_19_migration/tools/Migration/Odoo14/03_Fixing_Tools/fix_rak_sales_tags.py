
import xmlrpc.client
import argparse
import logging

logging.basicConfig(level=logging.INFO, format='%(message)s')
logger = logging.getLogger(__name__)

def fix_rak_sales(url, db, user, password):
    common = xmlrpc.client.ServerProxy('{}/xmlrpc/2/common'.format(url))
    uid = common.authenticate(db, user, password, {})
    models = xmlrpc.client.ServerProxy('{}/xmlrpc/2/object'.format(url))
    
    # RAK ID = 2
    cid = 2
    
    # RAK Tags
    # Base: 1(f)B -> ID 15
    # Tax:  1(f)T -> ID 14
    base_tag_id = 15
    tax_tag_id = 14
    
    # Find Purchase Tax used on Sales: ID 74 "VAT PRAK"
    try:
        tax_prak = models.execute_kw(db, uid, password, 'account.tax', 'read', [74], {'fields': ['name', 'amount']})[0]
        logger.info(f"Targeting Tax: {tax_prak['name']} ({tax_prak['amount']}%)")
    except:
        logger.error("Tax ID 74 not found!")
        return
        
    # Also target ID 73 "VAT 5% RAK" just in case it was missed
    target_tax_ids = [74, 73]
    
    # Find Sales Invoices since 2025
    domain = [
        ('company_id', '=', cid),
        ('move_type', 'in', ['out_invoice', 'out_refund']),
        ('state', '=', 'posted'),
        ('date', '>=', '2025-01-01')
    ]
    move_ids = models.execute_kw(db, uid, password, 'account.move', 'search', [domain])
    logger.info(f"Found {len(move_ids)} Sales Invoices in RAK since 2025-01-01")
    
    if not move_ids:
        return
        
    # Batch Process
    batch_size = 50
    updated_base = 0
    updated_tax = 0
    
    for i in range(0, len(move_ids), batch_size):
        batch = move_ids[i:i+batch_size]
        
        # A. Base Lines (lines using the tax)
        base_line_ids = models.execute_kw(db, uid, password, 'account.move.line', 'search', [[
            ('move_id', 'in', batch),
            ('tax_ids', 'in', target_tax_ids) 
        ]])
        
        if base_line_ids:
            models.execute_kw(db, uid, password, 'account.move.line', 'write', [base_line_ids, {'tax_tag_ids': [(4, base_tag_id)]}])
            updated_base += len(base_line_ids)
            
        # B. Tax Lines (lines generated by the tax)
        tax_line_ids = models.execute_kw(db, uid, password, 'account.move.line', 'search', [[
            ('move_id', 'in', batch),
            ('tax_line_id', 'in', target_tax_ids)
        ]])
        
        if tax_line_ids:
            models.execute_kw(db, uid, password, 'account.move.line', 'write', [tax_line_ids, {'tax_tag_ids': [(4, tax_tag_id)]}])
            updated_tax += len(tax_line_ids)
            
    logger.info(f"Updated: {updated_base} Base Lines, {updated_tax} Tax Lines.")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument('--url', default='https://metro.equdaierp.com')
    parser.add_argument('--db', default='metrodb')
    parser.add_argument('--user', default='admin')
    parser.add_argument('--password', default='Amaze@321')
    args = parser.parse_args()
    
    fix_rak_sales(args.url, args.db, args.user, args.password)
